/**
 * pro_fetch_fetch_raw — Fetch URL and return raw body without processing
 * Pack: http (REAL ✅) (pro-fetch)
 */
import { defineTool } from '../../core/tool.js';
import { view } from '../../core/input.js';
export default defineTool({
  name: 'pro_fetch_fetch_raw',
  description: 'Fetch URL and return raw body without processing',
  category: 'http',
  inputSchema: {
    type: 'object',
    properties: {
      url: { type: 'string', description: 'Manzil (URL)' },
    },
    required: ['url'],
  },
  async handler(input) {
    const p = view(input);
    const r = await fetchWithOptions(String(p.url));
    if (r.status >= 400) return fail('HTTP ' + r.status);
    return md(r.text, 12000);
  },
});
